import { mkdtemp, readFile, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { FrameworkApplication, Schema } from '@ultimabase/core'
import { afterEach, describe, expect, it } from 'vitest'

import { typegenPlugin } from './plugin.js'

const temporaryDirectories: string[] = []

const createTemporaryDirectory = async (): Promise<string> => {
	const directory = await mkdtemp(path.join(os.tmpdir(), 'ultimabase-start-'))

	temporaryDirectories.push(directory)

	return directory
}

afterEach(async () => {
	await Promise.all(
		temporaryDirectories
			.splice(0)
			.map((directory) => rm(directory, { force: true, recursive: true })),
	)
})

describe('typegenPlugin', () => {
	it('regenerates the complete declaration during application startup', async () => {
		const directory = await createTemporaryDirectory()
		const outputPath = path.join(
			directory,
			'.ultimabase',
			'schema.generated.d.ts',
		)
		const Todo = Schema.define({
			className: 'GeneratedTodo',
			fields: (field) => ({
				title: field.string({ validation: { required: true } }),
				completed: field.boolean({ default: false }),
			}),
		})
		const application = new FrameworkApplication({
			plugins: [
				typegenPlugin({
					applicationId: 'fixture.todo',
					outputPath,
				}),
			],
			schemas: [Todo],
		})

		await application.start()

		const contents = await readFile(outputPath, 'utf8')

		expect(contents).toContain('Generated by @ultimabase/typegen')
		expect(contents).toContain('export type GeneratedTodoItem')
		expect(contents).toContain('readonly completed: boolean | null')
		expect(contents).not.toContain('export type ApplicationFieldBuilder')
		expect(application.getPlugin('@ultimabase/typegen')).toMatchObject({
			outputPath,
		})

		await application.dispose()
	})

	it('captures its output identity before caller-owned options can change', async () => {
		const directory = await createTemporaryDirectory()
		const outputPath = path.join(directory, 'schema.generated.d.ts')
		const ignoredPath = path.join(directory, 'ignored.generated.d.ts')
		const options: {
			applicationId: string
			outputPath: string
		} = {
			applicationId: 'fixture.original',
			outputPath,
		}
		const plugin = typegenPlugin(options)

		options.applicationId = 'fixture.changed'
		options.outputPath = ignoredPath

		const application = new FrameworkApplication({
			plugins: [plugin],
			schemas: [],
		})

		await application.start()

		const contents = await readFile(outputPath, 'utf8')

		expect(contents).toContain('readonly application: true')
		await expect(readFile(ignoredPath, 'utf8')).rejects.toMatchObject({
			code: 'ENOENT',
		})

		await application.dispose()
	})
})

import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

import type { SchemaTypegenError } from './errors.js'
import {
	readGeneratedTypeFingerprint,
	writeGeneratedTypeFile,
	writeGeneratedTypeFiles,
} from './writer.js'

const temporaryDirectories: string[] = []
const fingerprint = 'a'.repeat(64)
const replacementFingerprint = 'b'.repeat(64)
const declaration = (value: string, hash = fingerprint): string =>
	`// Generated by @ultimabase/typegen. Do not edit.\n// @ultimabase/schema-fingerprint sha256:${hash}\nexport type Value = ${JSON.stringify(value)}\n`

const createTemporaryDirectory = async (): Promise<string> => {
	const directory = await mkdtemp(path.join(os.tmpdir(), 'ultimabase-typegen-'))

	temporaryDirectories.push(directory)

	return directory
}

afterEach(async () => {
	await Promise.all(
		temporaryDirectories
			.splice(0)
			.map((directory) => rm(directory, { force: true, recursive: true })),
	)
})

describe('generated type file writer', () => {
	it('reads fingerprints and detects stale generated contents', () => {
		expect(readGeneratedTypeFingerprint(declaration('current'))).toBe(
			fingerprint,
		)
		expect(
			readGeneratedTypeFingerprint(
				declaration('stale', replacementFingerprint),
			),
		).not.toBe(fingerprint)
		expect(readGeneratedTypeFingerprint('export type Missing = true')).toBe(
			undefined,
		)
	})

	it('atomically replaces one complete sibling file', async () => {
		const directory = await createTemporaryDirectory()
		const outputPath = path.join(directory, 'generated', 'schema.d.ts')

		await writeGeneratedTypeFile({
			applicationId: 'fixture.application',
			contents: declaration('first'),
			outputPath,
		})
		await writeGeneratedTypeFile({
			applicationId: 'fixture.application',
			contents: declaration('second', replacementFingerprint),
			outputPath,
		})

		expect(await readFile(outputPath, 'utf8')).toBe(
			declaration('second', replacementFingerprint),
		)
		expect(await readdir(path.dirname(outputPath))).toStrictEqual([
			'schema.d.ts',
		])
	})

	it('rejects duplicate destinations before writing any output', async () => {
		const directory = await createTemporaryDirectory()
		const outputPath = path.join(directory, 'schema.d.ts')
		const expected: Partial<SchemaTypegenError> = {
			code: 'SCHEMA_TYPEGEN_FAILED',
			owner: 'fixture.second',
			path: outputPath,
			reason: 'output-path-conflict',
		}

		await expect(
			writeGeneratedTypeFiles([
				{
					applicationId: 'fixture.first',
					contents: declaration('first'),
					outputPath,
				},
				{
					applicationId: 'fixture.second',
					contents: declaration('second'),
					outputPath: path.join(directory, '.', 'schema.d.ts'),
				},
			]),
		).rejects.toMatchObject(expected)
		await expect(readFile(outputPath, 'utf8')).rejects.toMatchObject({
			code: 'ENOENT',
		})
	})
})

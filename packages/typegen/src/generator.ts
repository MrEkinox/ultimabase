import { createHash } from 'node:crypto'

import { generatedApplicationContractVersion } from '@ultimabase/core'
import type {
	FrameworkApplication,
	PluginDefinition,
	SchemaDefinition,
} from '@ultimabase/core'
import { immutableArray, immutableRecord } from '@ultimabase/shared'

import { renderSharedTypes } from './generator/filters/shared.js'
import { GeneratedIdentifiers } from './generator/identifiers.js'
import { ReferenceImports } from './generator/imports.js'
import {
	renderFieldBuilder,
	renderRegistry,
	renderSchemas,
} from './generator/registry.js'
import { renderSchemaPublic } from './generator/schema.js'
import type { RenderContext } from './generator/types.js'
import {
	renderContributedDeclarations,
	renderStandaloneDeclarations,
} from './generator/contributions.js'
import {
	createTypegenSnapshot,
	type TypegenApplicationSnapshot,
} from './snapshot.js'

const generatorVersion = 11

const fingerprintSnapshot = (snapshot: TypegenApplicationSnapshot): string =>
	createHash('sha256')
		.update(
			JSON.stringify({
				coreContractVersion: generatedApplicationContractVersion,
				generatorVersion,
				snapshot,
			}),
		)
		.digest('hex')

export interface GeneratedApplicationTypes {
	/** Complete deterministic TypeScript declaration ready for atomic output. */
	readonly contents: string
	/** SHA-256 identity of the generator, Core ABI, and static application graph. */
	readonly fingerprint: string
	/** Immutable callback-free logical input used to produce the declaration. */
	readonly snapshot: TypegenApplicationSnapshot
	/** Separately owned inert outputs requested through `typegen:emit`. */
	readonly outputs: readonly GeneratedTypegenOutput[]
}

export interface GeneratedTypegenOutput {
	readonly contents: string
	readonly contributionId: string
	readonly fingerprint: string
	readonly kind: 'declaration' | 'metadata'
	readonly outputPath: string
	readonly owner: string
}

export interface GenerateApplicationTypesOptions {
	/** Compiles the exact application schema graph without running plugin setup. */
	readonly application: FrameworkApplication<
		readonly SchemaDefinition[],
		readonly PluginDefinition[]
	>
	/** Isolates fingerprints and generated registries owned by different applications. */
	readonly applicationId: string
}

/** Renders one previously validated static snapshot without touching application state. */
export const generateApplicationTypesFromSnapshot = (
	snapshot: TypegenApplicationSnapshot,
): GeneratedApplicationTypes => {
	const fingerprint = fingerprintSnapshot(snapshot)
	const imports = new ReferenceImports(snapshot)
	const identifiers = new GeneratedIdentifiers(snapshot)
	const schemasByName = new Map(
		snapshot.schemas.map((schema) => [schema.className, schema]),
	)
	const context: RenderContext = { identifiers, imports, schemasByName }
	const generatedSections = [
		...snapshot.schemas.map((schema) => renderSchemaPublic(schema, context)),
		renderContributedDeclarations(snapshot, context),
		renderSharedTypes(snapshot, context),
		renderFieldBuilder(snapshot, context),
		renderSchemas(snapshot, context),
		'// Framework registry',
		renderRegistry(snapshot, context),
	].filter((section) => section !== '')
	const sections = [
		`/* eslint-disable */\n\n// Generated by @ultimabase/typegen. Do not edit.\n// @ultimabase/schema-fingerprint sha256:${fingerprint}`,
		generatedSections.some((section) => section.includes('Core.'))
			? `import type * as Core from '@ultimabase/core'`
			: '',
		imports.render(),
		...generatedSections,
	].filter((section) => section !== '')
	const contents = `${sections.join('\n\n')}\n`
	const outputs = immutableArray(
		snapshot.outputs.map((output) => {
			const outputFingerprint = createHash('sha256')
				.update(
					JSON.stringify({
						applicationFingerprint: fingerprint,
						output,
					}),
				)
				.digest('hex')
			const owner =
				output.owner.instanceId === undefined
					? output.owner.pluginId
					: `${output.owner.pluginId}#${output.owner.instanceId}`
			const outputContents =
				output.kind === 'declaration'
					? `${[
							'/* eslint-disable */',
							'// Generated by @ultimabase/typegen. Do not edit.',
							`// @ultimabase/schema-fingerprint sha256:${outputFingerprint}`,
							imports.render(),
							renderStandaloneDeclarations(output.declarations ?? [], context),
						]
							.filter((section) => section !== '')
							.join('\n\n')}\n`
					: `${JSON.stringify(
							{
								'@ultimabase/schema-fingerprint': `sha256:${outputFingerprint}`,
								applicationId: snapshot.applicationId,
								contributionId: output.contributionId,
								metadata: output.metadata,
								owner,
							},
							null,
							2,
						)}\n`
			return immutableRecord({
				contents: outputContents,
				contributionId: output.contributionId,
				fingerprint: outputFingerprint,
				kind: output.kind,
				outputPath: output.outputPath,
				owner,
			})
		}),
	)

	return immutableRecord({ contents, fingerprint, outputs, snapshot })
}

/** Emits one deterministic, callback-free application declaration registry. */
export const generateApplicationTypes = (
	options: GenerateApplicationTypesOptions,
): GeneratedApplicationTypes =>
	generateApplicationTypesFromSnapshot(
		createTypegenSnapshot(options.application, options.applicationId),
	)

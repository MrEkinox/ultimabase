import { FrameworkError, type OperationKind } from '@ultimabase/core'

import {
	readPostgresDriverCode,
	readPostgresDriverConstraint,
} from '../connection/driver-error.js'

const isFrameworkError = (value: unknown): value is FrameworkError =>
	value instanceof FrameworkError

/** SQLSTATE 40001 and 40P01 guarantee that PostgreSQL rolled the transaction back. */
const isSerializationFailure = (driverCode: string | undefined): boolean =>
	driverCode === '40001' || driverCode === '40P01'

/** Describes one adapter-generated constraint in logical names. */
export type PostgresConstraintDescription =
	| Readonly<{
			kind: 'unique'
			/** The public schema owning the index; absent for private tables. */
			schema?: string
			/** The private collection owning the index. */
			collection?: string
			fields: readonly string[]
	  }>
	| Readonly<{
			kind: 'reference'
			schema?: string
			collection?: string
			field: string
			target: string
	  }>

/** Resolves one physical constraint name generated by this adapter. */
export type PostgresConstraintLookup = (
	name: string,
) => PostgresConstraintDescription | undefined

/** Names the logical operation target so errors never need SQL identifiers. */
export interface PostgresOperationErrorScope {
	readonly constraints?: PostgresConstraintLookup
	readonly schema?: string
}

/** Names the logical target of a statement for neutral storage errors. */
export const readPostgresErrorScope = (
	context: Readonly<{
		constraints?: PostgresConstraintLookup | undefined
		schema: Readonly<{ definition: Readonly<{ className: string }> }>
	}>,
): PostgresOperationErrorScope => ({
	schema: context.schema.definition.className,
	...(context.constraints === undefined
		? {}
		: { constraints: context.constraints }),
})

const describeConstraint = (
	error: unknown,
	scope: PostgresOperationErrorScope,
): PostgresConstraintDescription | undefined => {
	const constraint = readPostgresDriverConstraint(error)

	return constraint === undefined ? undefined : scope.constraints?.(constraint)
}

/** Reports a duplicate unique index value with its logical index fields only. */
export const createPostgresUniqueViolation = (
	error: unknown,
	internalDetails: Readonly<Record<string, unknown>>,
	scope: PostgresOperationErrorScope,
): FrameworkError<'UNIQUE_VIOLATION'> => {
	const description = describeConstraint(error, scope)
	const index =
		description?.kind === 'unique' && description.schema !== undefined
			? { schema: description.schema, fields: description.fields }
			: undefined

	return new FrameworkError(
		'UNIQUE_VIOLATION',
		'PostgreSQL rejected a duplicate unique index value.',
		{
			cause: error,
			publicMessage:
				index === undefined
					? 'The operation would duplicate a unique value.'
					: `A ${index.schema} with the same ${index.fields.join(', ')} already exists.`,
			...(index === undefined ? {} : { publicDetails: index }),
			internalDetails: {
				...internalDetails,
				...(description?.kind === 'unique' &&
				description.collection !== undefined
					? { collection: description.collection, fields: description.fields }
					: {}),
			},
		},
	)
}

/**
 * Reports a referential-integrity failure (ADR-0299) naming only the schema of
 * the row being deleted or written; referencing rows may be invisible.
 */
export const createPostgresReferenceViolation = (
	error: unknown,
	deletion: boolean,
	internalDetails: Readonly<Record<string, unknown>>,
	scope: PostgresOperationErrorScope,
): FrameworkError<'REFERENCE_VIOLATION'> => {
	const description = describeConstraint(error, scope)
	const subject =
		scope.schema === undefined ? 'object' : `${scope.schema} object`

	return new FrameworkError(
		'REFERENCE_VIOLATION',
		deletion
			? 'PostgreSQL restricted the deletion of a referenced row.'
			: 'PostgreSQL rejected a reference to a missing row.',
		{
			cause: error,
			publicMessage: deletion
				? `The ${subject} cannot be deleted while other objects reference it.`
				: `The ${subject} references an object that does not exist.`,
			...(scope.schema === undefined
				? {}
				: { publicDetails: { schema: scope.schema } }),
			internalDetails: {
				...internalDetails,
				...(description?.kind === 'reference'
					? {
							referencedSchema: description.target,
							referencingField: description.field,
							...(description.schema === undefined
								? {}
								: { referencingSchema: description.schema }),
							...(description.collection === undefined
								? {}
								: { referencingCollection: description.collection }),
						}
					: {}),
			},
		},
	)
}

/** Reports a transient conflict that Core may retry (ADR-0300). */
export const createPostgresTransactionConflict = (
	error: unknown,
	internalDetails: Readonly<Record<string, unknown>>,
): FrameworkError<'TRANSACTION_CONFLICT'> =>
	new FrameworkError(
		'TRANSACTION_CONFLICT',
		'PostgreSQL aborted the transaction after a serialization failure or deadlock.',
		{
			cause: error,
			publicMessage:
				'The operation conflicted with a concurrent operation. Retry it.',
			internalDetails,
			retryable: true,
		},
	)

/** Reads the neutral storage failure of one driver error, if it has one (ADR-0302). */
export const mapPostgresStorageError = (
	error: unknown,
	deletion: boolean,
	internalDetails: Readonly<Record<string, unknown>>,
	scope: PostgresOperationErrorScope,
): FrameworkError | undefined => {
	const driverCode = readPostgresDriverCode(error)

	if (driverCode === '23505') {
		return createPostgresUniqueViolation(error, internalDetails, scope)
	}

	if (driverCode === '23503') {
		return createPostgresReferenceViolation(
			error,
			deletion,
			internalDetails,
			scope,
		)
	}

	return isSerializationFailure(driverCode)
		? createPostgresTransactionConflict(error, internalDetails)
		: undefined
}

/** Converts driver failures without exposing SQL, values, or database diagnostics. */
export const mapPostgresOperationError = (
	error: unknown,
	operation: OperationKind,
	scope: PostgresOperationErrorScope = {},
): FrameworkError => {
	if (isFrameworkError(error)) {
		return error
	}

	const driverCode = readPostgresDriverCode(error)
	const constraint = readPostgresDriverConstraint(error)
	const internalDetails = {
		...(driverCode === undefined ? {} : { driverCode }),
		...(constraint === undefined ? {} : { constraint }),
		operation,
	}

	if (driverCode === 'P0002') {
		return new FrameworkError('NOT_FOUND', 'PostgreSQL row was not found.', {
			cause: error,
			publicMessage: 'The requested object was not found.',
			internalDetails,
		})
	}

	const storageError = mapPostgresStorageError(
		error,
		operation === 'delete-one' || operation === 'delete-many',
		internalDetails,
		scope,
	)
	if (storageError !== undefined) return storageError

	// Other data exceptions (22) and integrity violations (23) come from developer values.
	if (
		driverCode?.startsWith('22') === true ||
		driverCode?.startsWith('23') === true
	) {
		return new FrameworkError(
			'VALIDATION_ERROR',
			'PostgreSQL rejected an operation value or constraint.',
			{
				cause: error,
				publicMessage: 'The operation violates a data constraint.',
				internalDetails,
			},
		)
	}

	return new FrameworkError('INTERNAL_ERROR', 'PostgreSQL operation failed.', {
		cause: error,
		publicMessage: 'The database operation failed.',
		internalDetails,
	})
}

/** Maps one statement failure with the schema and constraints of its context. */
export const mapPostgresStatementError = (
	error: unknown,
	operation: OperationKind,
	context: Parameters<typeof readPostgresErrorScope>[0],
): FrameworkError =>
	mapPostgresOperationError(error, operation, readPostgresErrorScope(context))

/** Removes SQL and connection diagnostics from transaction lifecycle failures. */
export const createPostgresTransactionError = (
	phase: 'begin' | 'commit' | 'rollback',
	error: unknown,
): FrameworkError<'TRANSACTION_CONFLICT' | 'TRANSACTION_ERROR'> => {
	const driverCode = readPostgresDriverCode(error)
	const internalDetails = {
		kind: 'postgres-transaction-failed',
		phase,
		...(driverCode === undefined ? {} : { driverCode }),
	}

	// A serialization failure reported by BEGIN or COMMIT means PostgreSQL rolled back.
	if (phase !== 'rollback' && isSerializationFailure(driverCode)) {
		return createPostgresTransactionConflict(error, internalDetails)
	}

	return new FrameworkError(
		'TRANSACTION_ERROR',
		`PostgreSQL transaction ${phase} failed.`,
		{
			publicMessage: 'The database transaction failed.',
			// Only a failed BEGIN is known not to have committed developer work.
			retryable: phase === 'begin' && driverCode?.startsWith('08') === true,
			internalDetails,
		},
	)
}

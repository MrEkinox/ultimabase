// Regenerates packages/graphql-explorer-plugin/src/graphiql-assets.ts: the
// GraphiQL import map with a sha384 integrity hash for every module the page
// loads (ADR-0325). Run `node tooling/graphiql-integrity/run.mjs` after
// changing a pinned version below, then review and commit the diff.
import console from 'node:console'
import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { URL } from 'node:url'

const esm = 'https://esm.sh'
// Bare specifiers the page and its modules import, pinned to final builds.
const imports = {
	'@emotion/is-prop-valid': 'data:text/javascript,',
	'@graphiql/react': `${esm}/@graphiql/react@0.37.7/X-ZUBlbW90aW9uL2lzLXByb3AtdmFsaWQsQGdyYXBoaXFsL3Rvb2xraXQsZ3JhcGhxbCxyZWFjdCxyZWFjdC1kb20/es2022/react.bundle.mjs`,
	'@graphiql/react/setup-workers/esm.sh': `${esm}/@graphiql/react@0.37.7/es2022/setup-workers/esm.sh.bundle.mjs`,
	'@graphiql/toolkit': `${esm}/@graphiql/toolkit@0.12.1/X-ZWdyYXBocWw/es2022/toolkit.bundle.mjs`,
	graphiql: `${esm}/graphiql@5.2.4/X-ZUBncmFwaGlxbC9yZWFjdCxncmFwaHFsLHJlYWN0LHJlYWN0LWRvbQ/es2022/graphiql.bundle.mjs`,
	graphql: `${esm}/graphql@17.0.2/es2022/graphql.bundle.mjs`,
	react: `${esm}/react@19.2.8/es2022/react.mjs`,
	'react-dom': `${esm}/react-dom@19.2.8/es2022/react-dom.mjs`,
	'react-dom/client': `${esm}/react-dom@19.2.8/es2022/client.mjs`,
	'react/jsx-runtime': `${esm}/react@19.2.8/es2022/jsx-runtime.mjs`,
	// Version ranges esm.sh leaves in its builds, pinned so every hash holds.
	[`${esm}/graphql-ws@%3E=%204.5.0?external=graphql&target=es2022`]: `${esm}/graphql-ws@6.3.0/X-ZWdyYXBocWw/es2022/graphql-ws.mjs`,
	[`${esm}/monaco-graphql/esm/graphql.worker.js?worker&deps=monaco-editor@0.52.2`]: `${esm}/monaco-graphql@1.9.0/esm/graphql.worker.js?worker&deps=monaco-editor@0.52.2`,
	[`${esm}/scheduler@%5E0.27.0?target=es2022`]: `${esm}/scheduler@0.27.0/es2022/scheduler.mjs`,
}
const userAgent = 'Mozilla/5.0 (Macintosh) AppleWebKit/537.36 Chrome/120'

// The lexer Vite and Vitest already install: it reads real import
// statements only, never one written inside a string (worker source).
const { init, parse } = await import('es-module-lexer')
await init

/** Resolves one import like the browser does with the import map above. */
const resolve = (specifier, parent) => {
	if (Object.hasOwn(imports, specifier)) return imports[specifier]
	if (!/^(?:\/|\.\.?\/|https:)/u.test(specifier)) return undefined
	const url = new URL(specifier, parent).href
	return imports[url] ?? url
}

const integrity = new Map()
const queue = Object.values(imports).filter((url) => url.startsWith('https:'))
while (queue.length > 0) {
	const url = queue.shift()
	if (integrity.has(url)) continue
	const response = await globalThis.fetch(url, {
		headers: { 'user-agent': userAgent },
	})
	if (!response.ok) throw new Error(`${url} answered ${response.status}`)
	const source = await response.text()
	integrity.set(
		url,
		`sha384-${createHash('sha384').update(source).digest('base64')}`,
	)
	for (const { n: specifier } of parse(source)[0]) {
		const target = specifier === undefined ? undefined : resolve(specifier, url)
		if (target?.startsWith('https:')) queue.push(target)
	}
}

const sorted = (record) =>
	Object.fromEntries(
		Object.entries(record).sort(([left], [right]) => left.localeCompare(right)),
	)
const output = `// Generated by tooling/graphiql-integrity/run.mjs. Do not edit.

/** Pins every GraphiQL module to one esm.sh build (ADR-0325). */
export const graphiqlImports: Readonly<Record<string, string>> = ${JSON.stringify(sorted(imports), null, '\t')}

/** The sha384 integrity of every module the GraphiQL page loads (ADR-0325). */
export const graphiqlIntegrity: Readonly<Record<string, string>> = ${JSON.stringify(sorted(Object.fromEntries(integrity)), null, '\t')}
`
const target = path.join(
	import.meta.dirname,
	'../../packages/graphql-explorer-plugin/src/graphiql-assets.ts',
)
await writeFile(target, output)
console.log(`wrote ${String(integrity.size)} integrity hashes to ${target}`)
